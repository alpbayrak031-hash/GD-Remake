"""Builds gd/deco_table.py: how to draw each decoration object, as a plain shape.

    python3 tools/make_deco_table.py path/to/object.json

object.json is Open-GD/OpenGD's Content/Custom/object.json (an open-source Geometry
Dash reimplementation, GPL-3.0); for every object ID it lists the game's own sprite
names, default colour channel and layer.  Only facts are taken from it - which simple
shape an object's sprite family looks like, its size where the file gives one, its
default colour channel and whether it sits behind or in front of the level - and no
sprite, name or image ends up in this project.  The shapes are my own reading of the
sprite names: an approximation for drawing, never used by the physics.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "gd", "deco_table.py")

# sprite-name prefix -> shape; first match wins.  None: not drawn (GD draws these
# see-through or animated - glows, gradients, fire, particles - which a canvas
# without transparency would turn into solid blots)
FAMILIES = (
    (("d_gradient", "lighttriangle", "d_scalefadering", "fire", "gj_drops", "d_spiral", "lightglow",
      "glow", "d_glow", "d_art", "d_sign", "d_arrow", "d_exmark", "d_qmark", "d_skull", "d_heart",
      "particle", "d_wave", "d_rays", "d_fan", "d_light", "emptyframe", "edit_"), None),
    (("block006_slope", "block009b_slope", "block009c_slope", "block012_slope"), "slope"),
    (("blockoutline", "persp_outline", "smalloutline"), "outline"),
    (("gridline",), "line"),
    (("fakespike",), "spike"),
    (("d_spikes", "pit_", "d_thorn", "d_spikeart", "d_grass"), "spikes"),
    (("d_small_ball", "d_ball", "d_circle", "d_spikewheel", "d_cogwheel", "d_wheel"), "circle"),
    (("d_link", "d_03_chain", "d_chain", "chain"), "chain"),
    (("d_cloud",), "cloud"),
    (("block", "square", "lightsquare", "d_square", "d_block", "brick", "tile", "d_smallbar", "lava",
      "colorsquare", "d_brick"), "block"),
)
DEFAULT_SIZE = {"block": (30, 30), "outline": (30, 30), "slope": (30, 30), "line": (30, 2), "spike": (30, 30),
                "spikes": (30, 12), "circle": (16, 16), "chain": (6, 30), "cloud": (40, 22)}


def shape_of(name):
    n = name.lower()
    for prefixes, shape in FAMILIES:
        if n.startswith(prefixes):
            return shape
    return None


def main(path):
    with open(path, encoding="utf-8") as fh:
        data = json.load(fh)
    rows = {}
    for key, o in data.items():
        if o.get("object_type") != 7:                  # 7: decoration (everything else has physics or is a trigger)
            continue
        name = o.get("texture_name") or ""
        children = o.get("children") or []
        if name in ("", "emptyFrame.png") and children:
            name = children[0].get("texture_name") or ""
        shape = shape_of(name)
        if shape is None:
            continue
        w, h = DEFAULT_SIZE[shape]
        sized = [c for c in [o] + children if "content_x" in c]
        if sized:
            w, h = sized[0]["content_x"], sized[0]["content_y"]
        if re.search(r"slope_02|slope_04", name):     # the long slopes cover two cells
            w = max(w, 60)
        behind = int(o.get("default_z_layer", 1)) < 5   # layers B4..B1 sit behind the gameplay, T1.. in front
        rows[int(key)] = (shape, float(w), float(h), int(o.get("default_primary_channel", 1004)), behind)
    lines = ['"""Generated by tools/make_deco_table.py - do not edit by hand.',
             "",
             "Decoration object id -> (shape, width, height, default colour channel, drawn behind the level).",
             '"""',
             "TABLE = {"]
    for oid in sorted(rows):
        shape, w, h, channel, behind = rows[oid]
        lines.append("    %d: (%r, %g, %g, %d, %s)," % (oid, shape, w, h, channel, behind))
    lines.append("}")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print("wrote %d decoration shapes to %s" % (len(rows), OUT))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
